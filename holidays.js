// Поточне відкрите свято
let openHolidayId = null;

// Рендер карток свят
function renderHolidays() {
    const grid = document.getElementById('holidays-grid');
    grid.innerHTML = holidayMenus.map(h => `
        <div class="holiday-card" onclick="openHolidayMenu(${h.id})">
            <span class="holiday-emoji">${h.icon}</span>
            <div class="holiday-info">
                <h3>${h.name}</h3>
                <p>${h.dishes.appetizers.length + h.dishes.salads.length + h.dishes.main.length + h.dishes.desserts.length} страв</p>
            </div>
            <span class="holiday-arrow">›</span>
        </div>
    `).join('');
}

// Відкрити меню свята
function openHolidayMenu(id) {
    const h = holidayMenus.find(x => x.id === id);
    if (!h) return;

    openHolidayId = id;

    // Приховати картки свят
    document.getElementById('holidays-grid').classList.add('hidden');

    // Показати меню
    const menu = document.getElementById('holiday-menu');
    menu.classList.remove('hidden');

    // Заголовок
    document.getElementById('holiday-title').innerHTML = `${h.icon} ${h.name}`;

    // Рендер страв
    const dishesContainer = document.getElementById('holiday-dishes');
    dishesContainer.innerHTML = `
        <p class="holiday-description">${h.description}</p>
        ${renderDishSection('🥗 Закуски', h.dishes.appetizers)}
        ${renderDishSection('🥬 Салати', h.dishes.salads)}
        ${renderDishSection('🍖 Основне', h.dishes.main)}
        ${renderDishSection('🍰 Десерти', h.dishes.desserts)}
    `;

    // Анімація появи
    menu.style.opacity = '0';
    menu.style.transform = 'translateY(20px)';
    requestAnimationFrame(() => {
        menu.style.transition = 'all 0.4s ease';
        menu.style.opacity = '1';
        menu.style.transform = 'translateY(0)';
    });
}

// Рендер секції страв
function renderDishSection(title, dishes) {
    if (!dishes.length) return '';
    return `
        <div class="dish-section">
            <h4 class="dish-section-title">${title}</h4>
            <div class="dish-list">
                ${dishes.map(d => `
                    <div class="dish-item" onclick="openDishRecipe('${escapeStr(d.name)}', '${escapeStr(d.emoji)}', ${JSON.stringify(d.ingredients).replace(/"/g, '&quot;')}, ${JSON.stringify(d.steps).replace(/"/g, '&quot;')})">
                        <span class="dish-emoji">${d.emoji}</span>
                        <span class="dish-name">${d.name}</span>
                        <span class="dish-arrow">→</span>
                    </div>
                `).join('')}
            </div>
        </div>
    `;
}

// Escape рядків для безпечного використання в HTML
function escapeStr(str) {
    return str.replace(/'/g, "\\'").replace(/"/g, '&quot;');
}

// Закрити меню свята
function closeHolidayMenu() {
    openHolidayId = null;
    document.getElementById('holiday-menu').classList.add('hidden');
    document.getElementById('holidays-grid').classList.remove('hidden');
}

// Відкрити рецепт страви з меню
function openDishRecipe(name, emoji, ingredients, steps) {
    const modal = document.createElement('div');
    modal.className = 'recipe-modal';
    modal.innerHTML = `
        <div class="modal-overlay" onclick="closeModal()"></div>
        <div class="modal-content">
            <button class="modal-close" onclick="closeModal()">✕</button>
            <div class="modal-header">
                <span class="modal-emoji">${emoji}</span>
                <h2>${name}</h2>
            </div>
            <div class="modal-section">
                <h3>Інгредієнти</h3>
                <ul class="modal-ingredients">
                    ${ingredients.map(i => `<li>${i}</li>`).join('')}
                </ul>
            </div>
            <div class="modal-section">
                <h3>Кроки приготування</h3>
                <ol class="modal-steps">
                    ${steps.map(s => `<li>${s}</li>`).join('')}
                </ol>
            </div>
        </div>`;

    document.body.appendChild(modal);
    document.body.style.overflow = 'hidden';
    requestAnimationFrame(() => modal.classList.add('active'));
}

