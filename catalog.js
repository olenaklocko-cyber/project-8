// Поточний фільтр
let currentFilter = 'all';
let searchQuery = '';

// Отримати відфільтровані рецепти
function getFilteredRecipes() {
    return recipes.filter(r => {
        const matchCategory = currentFilter === 'all' || r.category === currentFilter;
        const matchSearch = r.name.toLowerCase().includes(searchQuery.toLowerCase());
        return matchCategory && matchSearch;
    });
}

// Отримати назву категорії
function getCategoryName(category) {
    const names = { breakfast: 'Сніданок', lunch: 'Обід', dinner: 'Вечеря' };
    return names[category] || category;
}

// Отримати CSS клас тега
function getTagClass(category) {
    const classes = { breakfast: 'tag-breakfast', lunch: 'tag-lunch', dinner: 'tag-dinner' };
    return classes[category] || '';
}

