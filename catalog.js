function renderCatalog() {
    const grid = document.getElementById('catalog-grid');
    const filtered = getFilteredRecipes();

    if (filtered.length === 0) {
        grid.innerHTML = `
            <div class="empty-state" style="grid-column: 1/-1;">
                <div class="empty-icon">🔍</div>
                <p>Нічого не знайдено</p>
                <p class="empty-sub">Спробуйте інший запит або категорію</p>
            </div>`;
        return;
    }

    grid.innerHTML = filtered.map(r => `
        <div class="recipe-card" onclick="openRecipe(${r.id})">
            <div class="recipe-card-image">
                ${r.emoji}
            </div>
            <div class="recipe-card-body">
                <div class="recipe-card-title">${r.name}</div>
                <div class="recipe-card-meta">⏱️ ${r.time}</div>
                <span class="recipe-card-tag ${getTagClass(r.category)}">${getCategoryName(r.category)}</span>
            </div>
        </div>
    `).join('');
}

// Фільтр за категорією
function filterCategory(category) {
    currentFilter = category;
    document.querySelectorAll('.filter-btn').forEach(btn => btn.classList.remove('active'));
    event.target.classList.add('active');
    renderCatalog();
}

// Пошук рецептів
function searchRecipes(query) {
    searchQuery = query;
    renderCatalog();
}

// Відкрити рецепт (модальне вікно)
function openRecipe(id) {
    const r = recipes.find(x => x.id === id);
    if (!r) return;

    const modal = document.createElement('div');
    modal.className = 'recipe-modal';
    modal.innerHTML = `
        <div class="modal-overlay" onclick="closeModal()"></div>
        <div class="modal-content">
            <button class="modal-close" onclick="closeModal()">✕</button>
            <div class="modal-header">
                <span class="modal-emoji">${r.emoji}</span>
                <h2>${r.name}</h2>
                <span class="recipe-card-tag ${getTagClass(r.category)}">${getCategoryName(r.category)}</span>
                <span class="modal-time">⏱️ ${r.time}</span>
            </div>
            <p class="modal-desc">${r.description}</p>
            <div class="modal-section">
                <h3>Інгредієнти</h3>
                <ul class="modal-ingredients">
                    ${r.ingredients.map(i => `<li>${i}</li>`).join('')}
                </ul>
            </div>
            <div class="modal-section">
                <h3>Кроки приготування</h3>
                <ol class="modal-steps">
                    ${r.steps.map(s => `<li>${s}</li>`).join('')}
                </ol>
            </div>
        </div>`;

    document.body.appendChild(modal);
    document.body.style.overflow = 'hidden';
    requestAnimationFrame(() => modal.classList.add('active'));
}

// Закрити модальне вікно
function closeModal() {
    const modal = document.querySelector('.recipe-modal');
    if (modal) {
        modal.classList.remove('active');
        setTimeout(() => { modal.remove(); document.body.style.overflow = ''; }, 300);
    }
}

// Закрити по Escape
document.addEventListener('keydown', e => { if (e.key === 'Escape') closeModal(); });

// Ініціалізація
