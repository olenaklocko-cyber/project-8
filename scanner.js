// Допоміжна функція: перетворює короткий формат в повний
function toFull(r, idx) {
    return { id: 'local-' + idx, name: r.n, category: r.c, time: r.t, ingredients: r.i, steps: r.s, source: 'local', image: '' };
}

// ===== ПОШУК =====
function searchLocal(q) {
    const ql = q.toLowerCase();
    const results = [];
    LOCAL.forEach((r, idx) => {
        if (r.n.toLowerCase().includes(ql)) results.push(toFull(r, idx));
    });
    return results;
}

async function searchRecipes(query) {
    const container = document.getElementById('search-results');
    if (!container) return;
    if (query.length < 2) { container.innerHTML = '<p class="no-results">Почни вводити назву страви...</p>'; return; }
    container.innerHTML = '<div class="search-loading"><div class="loading-spinner small"></div>Шукаю...</div>';
    clearTimeout(searchTimeout);
    searchTimeout = setTimeout(async () => {
        const local = searchLocal(query);
        if (local.length > 0) {
            container.innerHTML = local.map(r => `
                <div class="search-result-card" onclick="showRecipe('${r.id}')">
                    <div class="search-result-info"><h4>${r.name}</h4>
                    <div class="search-result-meta">
                        <span class="note-tag">${r.category || ''}</span>
                        <span class="note-time">⏱ ${r.time} хв</span>
                    </div></div></div>
            `).join('');
        } else {
            container.innerHTML = `
                <div class="no-results-found">
                    <p>😕 Рецепт «${query}» не знайдено в нашій базі</p>
                    <p class="no-results-hint">Але можна знайти в інтернеті:</p>
                    <a href="https://www.google.com/search?q=${encodeURIComponent(query + ' рецепт українською мовою')}" target="_blank" class="google-search-btn">🔍 Знайти рецепт в Google</a>
                </div>`;
        }
    }, 400);
}

